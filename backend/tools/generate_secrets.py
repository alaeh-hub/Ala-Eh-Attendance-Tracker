"""
Generate the secrets a production deployment needs.

    cd backend
    .venv\\Scripts\\python tools\\generate_secrets.py            # print only
    .venv\\Scripts\\python tools\\generate_secrets.py --write .env  # write a ready .env

--write refuses to overwrite an existing file unless --force is given.
BACK UP THE OUTPUT (a password manager is fine). FACE_DATA_KEY encrypts
every face embedding, photo and snapshot: if it is lost, that data cannot
be recovered and every employee has to be re-enrolled.
"""
import argparse
import os
import secrets
import sys

from cryptography.fernet import Fernet

TEMPLATE = """# Generated by tools/generate_secrets.py - keep this file private and back it up.
APP_ENV=production
SECRET_KEY={secret_key}
JWT_SECRET_KEY={jwt_key}
FACE_DATA_KEY={face_key}

# PostgreSQL (docker-compose reads POSTGRES_PASSWORD from the same value)
POSTGRES_PASSWORD={db_password}
DATABASE_URL=postgresql+psycopg2://attendance:{db_password}@db:5432/attendance

# Browsers allowed to call the API (comma separated)
CORS_ORIGINS=http://localhost:5173

# Organisation
ORG_TIMEZONE=Asia/Manila
SHIFT_START=08:00
SHIFT_END=17:00
LATE_GRACE_MINUTES=15
ATTENDANCE_COOLDOWN_SECONDS=60

FACE_ENGINE=auto
LIVENESS_REQUIRED=true
SPOOF_MODE=auto
"""


def generate() -> dict:
    return {
        "secret_key": secrets.token_urlsafe(48),
        "jwt_key": secrets.token_urlsafe(48),
        "face_key": Fernet.generate_key().decode(),
        # URL-safe alphabet only: the value is embedded in DATABASE_URL.
        "db_password": secrets.token_urlsafe(24),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", metavar="PATH", help="write a complete .env to PATH")
    ap.add_argument("--force", action="store_true", help="overwrite PATH if it exists")
    args = ap.parse_args()

    content = TEMPLATE.format(**generate())
    if not args.write:
        print(content)
        return
    if os.path.exists(args.write) and not args.force:
        sys.exit(f"{args.write} already exists. Use --force to overwrite it (this replaces your current secrets).")
    with open(args.write, "w", encoding="utf-8") as fh:
        fh.write(content)
    print(f"Wrote {args.write}. Back up FACE_DATA_KEY now: losing it makes all stored face data unreadable.")


if __name__ == "__main__":
    main()
